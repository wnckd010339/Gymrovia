function tableBase(x,y,w,cols,rows,widths) {
  let b = `${rect(x,y,w,56,C.soft,12)}${rect(x,y+44,w,rows.length*58+12,C.surface,0,C.line)}`;
  let px=x+20;
  cols.forEach((c,i)=>{b+=text(px,y+34,c,12,C.muted,700);px+=widths[i];});
  rows.forEach((row,ri)=>{
    const yy=y+88+ri*58; px=x+20;
    b+=line(x,yy-24,x+w,yy-24,C.line);
    row.forEach((v,i)=>{b+=text(px,yy,v,13,i===0?C.ink:C.muted,i===0?700:500);px+=widths[i];});
  });
  return b;
}

